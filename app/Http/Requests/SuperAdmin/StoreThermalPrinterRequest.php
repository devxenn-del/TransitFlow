<?php

namespace App\Http\Requests\SuperAdmin;

use App\Models\ThermalPrinter;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

/**
 * Register a printer into the platform inventory. The Thermal ID / Device
 * ID are generated server-side, so submitting either is refused outright
 * rather than silently ignored.
 */
class StoreThermalPrinterRequest extends FormRequest
{
    public function authorize(): bool
    {
        return $this->user()?->hasPermissionTo('printers.inventory.manage') ?? false;
    }

    protected function prepareForValidation(): void
    {
        if ($this->has('mac_address')) {
            $this->merge(['mac_address' => ThermalPrinter::normalizeMac($this->input('mac_address'))]);
        }
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'thermal_id' => ['prohibited'],
            'device_id' => ['prohibited'],
            'model' => ['required', 'string', 'max:100'],
            'mac_address' => ['nullable', 'string', 'regex:'.ThermalPrinter::MAC_ADDRESS_PATTERN, Rule::unique('thermal_printers', 'mac_address')],
            'serial_number' => ['nullable', 'string', 'max:40'],
            'remarks' => ['nullable', 'string', 'max:1000'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'thermal_id.prohibited' => 'The Thermal ID is generated by the system and cannot be set.',
            'device_id.prohibited' => 'The Device ID is generated by the system and cannot be set.',
            'mac_address.regex' => 'Enter the MAC address as six pairs of hex digits, e.g. 00:1A:2B:3C:4D:5E.',
            'mac_address.unique' => 'A printer with this MAC address is already registered.',
        ];
    }
}
